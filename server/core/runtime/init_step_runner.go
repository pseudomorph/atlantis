package runtime

import (
	"crypto/sha256"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/google/shlex"

	version "github.com/hashicorp/go-version"
	"github.com/runatlantis/atlantis/server/core/runtime/common"
	"github.com/runatlantis/atlantis/server/core/terraform"
	"github.com/runatlantis/atlantis/server/events/command"
	"github.com/runatlantis/atlantis/server/utils"
)

// InitStep runs `terraform init`.
type InitStepRunner struct {
	TerraformExecutor     TerraformExec
	DefaultTFDistribution terraform.Distribution
	DefaultTFVersion      *version.Version
}

func (i *InitStepRunner) Run(ctx command.ProjectContext, extraArgs []string, path string, envs map[string]string) (string, error) {
	// extra_args comes from configuration, so environment variable references
	// in it may be expanded. Comment args are not part of the init command and
	// must not influence its expansion policy.
	execCtx := ctx
	execCtx.ExpandableArgs = nil
	if len(extraArgs) > 0 {
		execCtx.ExpandableArgs = extraArgs
	}
	execCtx.CommentArgs = nil
	lockFileName := ".terraform.lock.hcl"
	terraformLockfilePath := filepath.Join(path, lockFileName)
	terraformLockFileTracked, err := common.IsFileTracked(path, lockFileName)
	if err != nil {
		ctx.Log.Warn("Error checking if %s is tracked in %s: %s", lockFileName, path, err)
	}
	// If .terraform.lock.hcl is not tracked in git and it exists prior to init
	// delete it as it probably has been created by a previous run of
	// terraform init
	if ctx.RestoredDataDirectory == "" && common.FileExists(terraformLockfilePath) && err == nil && !terraformLockFileTracked {
		ctx.Log.Debug("Deleting `%s` that was generated by previous terraform init", terraformLockfilePath)
		delErr := utils.RemoveIgnoreNonExistent(terraformLockfilePath)
		if delErr != nil {
			ctx.Log.Warn("Error Deleting `%s`: %s", lockFileName, delErr)
		}
	}

	tfDistribution := i.DefaultTFDistribution
	if ctx.TerraformDistribution != nil {
		tfDistribution = terraform.NewDistribution(*ctx.TerraformDistribution)
	}

	tfVersion := i.DefaultTFVersion
	if ctx.TerraformVersion != nil {
		tfVersion = ctx.TerraformVersion
	}

	if ctx.RestoredDataDirectory != "" {
		if ctx.RestoredLockHash != "" && !common.FileExists(terraformLockfilePath) {
			return "", fmt.Errorf("restored dependency lock file is missing; run plan again")
		}
		if ctx.RestoredLockHash != "" {
			root, err := os.OpenRoot(path)
			if err != nil {
				return "", err
			}
			locked, readErr := root.ReadFile(lockFileName)
			_ = root.Close()
			if readErr != nil {
				return "", readErr
			}
			if fmt.Sprintf("%x", sha256.Sum256(locked)) != ctx.RestoredLockHash {
				return "", fmt.Errorf("restored provider lock file changed before initialization; run plan again")
			}
		}
		dataDir, err := command.TerraformDataDirectory(path, envs)
		if err != nil {
			return "", err
		}
		if dataDir != ctx.RestoredDataDirectory {
			return "", fmt.Errorf("TF_DATA_DIR differs from the pending plan; run plan again")
		}
		if tfDistribution.BinName() == "terraform" && MustConstraint("< 0.14.0").Check(tfVersion.Core()) {
			return "", fmt.Errorf("automatic restored initialization requires Terraform >= 0.14")
		}
		effective := func(key string) string {
			if value, ok := envs[key]; ok {
				return value
			}
			if value, ok := os.LookupEnv(key); ok {
				return value
			}
			switch key {
			case "DIR":
				return path
			case "WORKSPACE":
				return ctx.Workspace
			case "ATLANTIS_TERRAFORM_VERSION":
				return tfVersion.String()
			}
			return ""
		}
		if selected := effective("TF_WORKSPACE"); selected != "" && selected != ctx.Workspace {
			return "", fmt.Errorf("TF_WORKSPACE differs from the pending plan")
		}
		arguments := make([]string, 0, len(extraArgs))
		for _, raw := range extraArgs {
			arguments = append(arguments, os.Expand(raw, effective))
		}
		for _, key := range []string{"TF_CLI_ARGS", "TF_CLI_ARGS_init"} {
			parsed, err := shlex.Split(effective(key))
			if err != nil {
				return "", fmt.Errorf("invalid %s for restored initialization", key)
			}
			arguments = append(arguments, parsed...)
		}
		for _, arg := range arguments {
			flag, value, _ := strings.Cut(strings.TrimLeft(arg, "-"), "=")
			switch flag {
			case "upgrade", "migrate-state", "force-copy", "reconfigure":
				return "", fmt.Errorf("restored initialization does not permit -%s", flag)
			case "lockfile":
				if value != "readonly" {
					return "", fmt.Errorf("restored initialization requires an unchanged dependency lock file")
				}
			}
		}
	}

	terraformInitVerb := []string{"init"}
	terraformInitArgs := []string{"-input=false"}
	if ctx.RestoredDataDirectory != "" && (tfDistribution.BinName() != "terraform" || MustConstraint(">= 0.15.0").Check(tfVersion.Core())) {
		terraformInitArgs = append(terraformInitArgs, "-lockfile=readonly")
	}

	// If we're running < 0.9 we have to use `terraform get` instead of `init`.
	if MustConstraint("< 0.9.0").Check(tfVersion) {
		ctx.Log.Info("running terraform version %s so will use `get` instead of `init`", tfVersion)
		terraformInitVerb = []string{"get"}
		terraformInitArgs = []string{}
	}

	if ctx.RestoredDataDirectory == "" && (MustConstraint("< 0.14.0").Check(tfVersion) || !common.FileExists(terraformLockfilePath)) {
		terraformInitArgs = append(terraformInitArgs, "-upgrade")
	}

	finalArgs := common.DeDuplicateExtraArgs(terraformInitArgs, extraArgs)

	terraformInitCmd := append(terraformInitVerb, finalArgs...)

	out, err := i.TerraformExecutor.RunCommandWithVersion(execCtx, path, terraformInitCmd, envs, tfDistribution, tfVersion, ctx.Workspace)
	// Only include the init output if there was an error. Otherwise it's
	// unnecessary and lengthens the comment.
	if err != nil {
		return out, err
	}
	return "", nil
}
